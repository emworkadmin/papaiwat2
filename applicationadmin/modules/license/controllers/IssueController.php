		if (!$sUser->hasData()) {
			$this->_helper->redirector('index', 'index', 'default');
		}
		if ($sUser->getInfo()->UserType != "B") {
			$this->_helper->redirector('index', 'index', 'default');
		}
		$canDelete = $sUser->isAllow('license.issue.manage');
		$canEdit = $sUser->isAllow('license.issue.manage');
		$canView = $sUser->isAllow('license.issue.view');
		if (!$canView) {
			$this->_helper->redirector('index', 'issue', 'license');
		}
		
		// Get Param
		$itemID = $this->_request->getParam ( 'itemid' );
		
		if (!$itemID) {
			$this->_helper->redirector('index', 'issue', 'eform');
		}
		
		$model = new License_Model_Issue();
		
		$languages = System_Model_Setting::getLanguages();
		$defaultLanguage = System_Model_Setting::getDefaultLanguage();
				
		// Get Data
		$data = $model->getInfo($itemID);

		if(!$data) {
			$this->_helper->redirector('index', 'issue', 'license');
		}
		
		$dataDetails = array();
		if (count($languages) > 0) {
			foreach ($languages as $lang) {
				$langCode = $lang['Code'];
				$detail = $model->getDataByLanguage($data->ID, $langCode);
				if (!empty($detail->Lang)) {
					$dataDetails[$langCode] = $detail;
				}
			}
		}

		// Get Option
        $modelOption = new License_Model_Category();
		$categoryOption = $modelOption->getOption($defaultLanguage["Code"]);
				
		// Send Rights to View
		$this->view->canDelete = $canDelete;
		$this->view->canEdit = $canEdit;
		
		// Send Option and lookup To View
		$this->view->defaultLanguage = $defaultLanguage['Code'];
		$this->view->defaultLanguageName = $defaultLanguage['Name'];
		$this->view->languages = $languages;
		$this->view->publishOption = $this->publishOption;
		$this->view->categoryOption = $categoryOption;
		
		$this->view->data = $data;
		$this->view->dataDetails = $dataDetails;
		
		// Set View
		$this->view->pageName = "ปรับปรุงประเด็น";
		$this->view->pageIcon = "glyphicon glyphicon-th-list";
		$this->view->subMenus = array ();
		$this->view->breadcrumb = array (
				array ('name' => 'หน้าแรก', 'url' => $this->view->url(array('module' => 'default', 'controller' => 'index', 'action' => 'index'), null, true )),
				array ('name' => 'รายการประเด็น', 'url' => $this->view->url ( array ('module' => 'license', 'controller' => 'issue', 'action' => 'index'), null, true)),
				array ('name' => 'ปรับปรุงประเด็น')
		);
		
		// Log Acion
		System_Model_Log::action("license.issue", "view", $dataDetails[$defaultLanguage["Code"]]->Name, $itemID);
	}

