						$selectDetail = $this->db->select ()
						->from(array('tbl'=>'weblink_item_detail'), array('Lang','Title','IntroText'))
						->where("tbl.ID = ? ", $id)
						;
						$stmtDetail = $this->db->query($selectDetail);
						$dataDetail = $stmtDetail->fetchAll();

						if(count($dataDetail)>0){
							foreach($dataDetail as $d){
								$form = array();
								$form['ID'] = $tmpID;
								$form['Lang'] = empty($d['Lang']) ? null : $d['Lang'];
								$form['Title'] = empty($d['Title']) ? null : $d['Title'];
								if($defaultLanguage == $d['Lang']){
									$form['Title'] = $form['Title'] . ' (Copy)';
								}
								$form['IntroText'] = empty($d['IntroText']) ? null : $d['IntroText'];
								$form['Created'] = $modified;
								$form['CreatedBy'] = $this->UserID;
								$this->db->insert("weblink_item_detail", $form);
							}
						}

						// Category Item
						$selectCatItem = $this->db->select ()
						->from(array('tbl'=>'weblink_category_item'), array('WeblinkCategoryID'))
						->where("tbl.WeblinkItemID = ? ", $id)
						;
						$stmtCatItem = $this->db->query($selectCatItem);
						$dataCatItem = $stmtCatItem->fetchAll();

						if(count($dataCatItem)>0){
							foreach($dataCatItem as $d){
								$form = array();
								$form['WeblinkItemID'] = $tmpID;
								$form['WeblinkCategoryID'] = empty($d['WeblinkCategoryID']) ? null : $d['WeblinkCategoryID'];
								$form['Created'] = $modified;
								$form['CreatedBy'] = $this->UserID;
								$this->db->insert("weblink_category_item", $form);
							}
						}

					}

				} // End Foreach
			} // End Count
			
		} catch (Exception $e) {
			$data->result = false;
			$data->message = $e->getMessage();
		}
		return $data;
	}

	function listDelete($params) {
		$data = new stdClass();
		$data->result = false;
		try {
			
			$modified = date("Y-m-d H:i:s");
			
			$affRow = 0;
			if (count($params['ids']) > 0) {
				foreach ($params['ids'] as $id) {
					$form = array ();
					$where = array ();
					$form['IsDeleted'] = 'Y';
					$form['Modified'] = $modified;
					$form['ModifiedBy'] = $this->UserID;
					$where['ID = ? '] = $id;
					$affRow += $this->db->update("weblink_item_info", $form, $where);
				}
			}
			
			$data->result = $affRow > 0;
			
		} catch (Exception $e) {
			$data->result = false;
			$data->message = $e->getMessage();
		}
		return $data;
	}
