			$this->_helper->redirector('index', 'index', 'default');
		}
		$canDelete = $sUser->isAllow('faq.category.manage');
		$canEdit = $sUser->isAllow('faq.category.manage');
		$canView = $sUser->isAllow('faq.category.view');
		if (!$canView) {
			$this->_helper->redirector('index', 'category', 'faq');
		}

		// Zend Filter
        $filterInt = new Zend_Filter_Int();
        
        // Get Param
		$itemID = $filterInt->filter($this->_request->getParam('itemid'));
		
		if (!$itemID) {
			$this->_helper->redirector('index', 'subcategory', 'faq');
		}
		
		$model = new Faq_Model_Subcategory();
		
		$languages = System_Model_Setting::getLanguages();
		$defaultLanguage = System_Model_Setting::getDefaultLanguage();
				
		// Get Data
		$data = $model->getInfo ( $itemID );
		
		$dataDetails = array();
		if (count($languages) > 0) {
			foreach ($languages as $lang) {
				$langCode = $lang['Code'];
				$detail = $model->getDataByLanguage($data->ID, $langCode);
				if (!empty($detail->Lang)) {
					$dataDetails[$langCode] = $detail;
				}
			}
		}

		// Get Option
		$modelCategory = new Faq_Model_Category();
		$FaqCategoryOption = $modelCategory->getOption($defaultLanguage["Code"]);
		
		// Send Rights to View
		$this->view->canDelete = $canDelete;
		$this->view->canEdit = $canEdit;
		
		// Send Option and lookup To View
		$this->view->defaultLanguage = $defaultLanguage['Code'];
		$this->view->defaultLanguageName = $defaultLanguage['Name'];
		$this->view->languages = $languages;
		$this->view->publishOption = $this->publishOption;
		$this->view->FaqCategoryOption = Emwork_Utility::addEmptyOption($FaqCategoryOption);
		
		$this->view->data = $data;
		$this->view->dataDetails = $dataDetails;
		
		// Set View
		$this->view->pageName = "ปรับปรุงหมวดหมู่รอง";
		$this->view->pageIcon = "glyphicon glyphicon-th-list";
		$this->view->breadcrumb = array (
				array ('name' => 'หน้าแรก', 'url' => $this->view->url(array('module' => 'default', 'controller' => 'index', 'action' => 'index'), null, true )),
				array ('name' => 'รายการหมวดหมู่รอง', 'url' => $this->view->url ( array ('module' => 'faq', 'controller' => 'subcategory', 'action' => 'index'), null, true)),
				array ('name' => 'ปรับปรุงหมวดหมู่รอง') 
		);
		
		// Log Acion
		System_Model_Log::action("faq.subcategory", "view", $dataDetails[$defaultLanguage["Code"]]->Name, $itemID);
	}

